/**
 * Design-token pipeline: tokens/*.json → generated CSS.
 *
 * Emits two artifacts consumed by every app's styles.css:
 *  - src/generated/tokens.css  — --atlas-* custom properties (:root light, .dark overrides)
 *  - src/generated/theme.css   — Tailwind v4 @theme block mapping utilities onto the vars
 *
 * Semantic tokens (bg/surface/text/text-muted/border) resolve to the light set at
 * :root and flip to the dark set under .dark — components only ever read semantics.
 */
import StyleDictionary from 'style-dictionary';

const PREFIX = 'atlas';

const cssVar = (token) => `--${PREFIX}-${token.path.join('-')}`;

const SEMANTIC_KEYS = ['bg', 'surface', 'text', 'text-muted', 'border'];

StyleDictionary.registerFormat({
  name: 'css/atlas-vars',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens;
    const isMode = (t, mode) => t.path[0] === 'color' && t.path[1] === mode;
    const base = all.filter((t) => !isMode(t, 'light') && !isMode(t, 'dark'));
    const light = all.filter((t) => isMode(t, 'light'));
    const dark = all.filter((t) => isMode(t, 'dark'));

    const line = (t) => `  ${cssVar(t)}: ${t.$value ?? t.value};`;
    // semantic aliases: --atlas-color-bg etc. point at the active mode's values
    const semantic = (tokens) =>
      tokens
        .filter((t) => SEMANTIC_KEYS.includes(t.path[2]))
        .map((t) => `  --${PREFIX}-color-${t.path[2]}: ${t.$value ?? t.value};`)
        .join('\n');

    return [
      '/* generated by build-tokens.mjs — do not edit by hand */',
      ':root {',
      base.map(line).join('\n'),
      light.map(line).join('\n'),
      semantic(light),
      '}',
      '',
      '.dark {',
      dark.map(line).join('\n'),
      semantic(dark),
      '}',
      '',
    ].join('\n');
  },
});

StyleDictionary.registerFormat({
  name: 'css/atlas-tailwind-theme',
  format: ({ dictionary }) => {
    const all = dictionary.allTokens;
    const entries = [];
    for (const t of all) {
      const [group, ...rest] = t.path;
      if (group === 'color') {
        if (t.path[1] === 'light' || t.path[1] === 'dark') continue; // semantics cover these
        entries.push(`  --color-${rest.join('-')}: var(${cssVar(t)});`);
      } else if (group === 'spacing') {
        entries.push(`  --spacing-${rest.join('-')}: var(${cssVar(t)});`);
      } else if (group === 'radius') {
        entries.push(`  --radius-${rest.join('-')}: var(${cssVar(t)});`);
      }
    }
    for (const key of SEMANTIC_KEYS) {
      entries.push(`  --color-${key}: var(--${PREFIX}-color-${key});`);
    }
    return [
      '/* generated by build-tokens.mjs — do not edit by hand */',
      '@theme inline {',
      entries.join('\n'),
      '}',
      '',
    ].join('\n');
  },
});

const sd = new StyleDictionary({
  source: ['libs/shared/design-tokens/tokens/*.json'],
  platforms: {
    css: {
      // full-path kebab names keep token names unique (both formats read `path` anyway)
      transforms: ['name/kebab'],
      buildPath: 'libs/shared/design-tokens/src/generated/',
      files: [
        { destination: 'tokens.css', format: 'css/atlas-vars' },
        { destination: 'theme.css', format: 'css/atlas-tailwind-theme' },
      ],
    },
  },
});

await sd.buildAllPlatforms();
console.log('tokens built: src/generated/{tokens.css,theme.css}');
